export const translateCommodity = (commodity: string, lang: Language): string => {
    if (!commodity) return '';
    const lowerCommodity = commodity.toLowerCase();
    
    // Find the English key that matches the start of the commodity name
    const key = Object.keys(translations.en).find(enKey => lowerCommodity.startsWith(enKey));
    
    if (key && translations[lang] && translations[lang][key]) {
        return translations[lang][key];
    }
    
    // Fallback to the original commodity name if no translation is found
    return commodity;
};
